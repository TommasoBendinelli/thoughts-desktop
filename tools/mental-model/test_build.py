"""build.py's Library note: found in the Library, rewritten with its generated-file line, only when it changed.

Run: python3 -m pytest tools/mental-model/test_build.py
"""
import importlib.util
import json
from pathlib import Path

spec = importlib.util.spec_from_file_location("mental_model_build", Path(__file__).with_name("build.py"))
build = importlib.util.module_from_spec(spec)
spec.loader.exec_module(build)


def library(docs: Path, files: dict[str, str]) -> None:
    """A Library with one Project whose default folder holds @p files (docs-root paths)."""
    for relative, text in files.items():
        (docs / relative).parent.mkdir(parents=True, exist_ok=True)
        (docs / relative).write_text(text)
    entries = [{"id": relative, "name": Path(relative).name, "relative_path": Path(relative).name} for relative in files]
    (docs / ".thoughts").mkdir(parents=True, exist_ok=True)
    (docs / ".thoughts/library-projects.json").write_text(json.dumps(
        {"projects": [{"name": "notes", "sources": [{"files": entries}]}], "pending": []}))


def test_the_note_is_found_in_the_library(tmp_path):
    assert build.library_note(tmp_path) is None  # no Library at all
    library(tmp_path, {".thoughts/projects/p1/default/agent-note-rules.md": "# Rules\n"})
    assert build.library_note(tmp_path) is None  # no Mental Model note yet
    library(tmp_path, {".thoughts/projects/p1/default/agent-note-rules.md": "# Rules\n",
                       ".thoughts/projects/p1/default/Mental-Model.md": "# Old\n"})
    assert build.library_note(tmp_path) == tmp_path / ".thoughts/projects/p1/default/Mental-Model.md"


def test_the_note_is_rewritten_as_generated_only_when_it_changed(tmp_path):
    note = tmp_path / "mental-model.md"
    note.write_text("# Old\n")
    page = "# Mental Model\n\nWritten on 16 November 2026.\n"
    assert build.write_note(note, page)
    text = note.read_text()
    # Agents' proposals are refused on a note whose first line says it is generated.
    assert text.startswith("<!-- Generated by Thoughts: ") and text.splitlines()[0].endswith("-->")
    assert text.endswith("\n\n" + page)
    assert not build.write_note(note, page + "\n")  # the same page: nothing written, no Sync needed
    assert [path.name for path in tmp_path.iterdir()] == ["mental-model.md"]  # no temporary file left
