PROMPT = Path(__file__).with_name("prompt.md")
# Settings for the copy of the page, next to the output: {"publish": "host:path"}.
COPY_TARGETS = "copy-targets.json"
# The Library note every agent and service reads; Refresh rewrites it, so it says it is generated.
LIBRARY_NOTE = "mental-model.md"
