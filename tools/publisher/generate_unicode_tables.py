"""Writes unicode_table.inc: the parts of Python's str methods the native
publisher needs (casefold, lower, isspace, isprintable), frozen from the
Python version the source publisher runs, so names compare and sort alike.

  python3 generate_unicode_tables.py
"""
import sys
from pathlib import Path

LAST = 0x10FFFF


def mapping(name, method):
    rows = []
    for code in range(LAST + 1):
        if 0xD800 <= code <= 0xDFFF:
            continue
        character = chr(code)
        mapped = getattr(character, method)()
        if mapped != character:
            assert 1 <= len(mapped) <= 3, (code, mapped)
            padded = [ord(c) for c in mapped] + [0] * (3 - len(mapped))
            rows.append("    {0x%X, %d, {0x%X, 0x%X, 0x%X}}," % (code, len(mapped), *padded))
    return ["static const CaseMapping %s[] = {" % name, *rows, "};"]


def ranges(name, predicate):
    rows = []
    start = None
    for code in range(LAST + 2):
        inside = code <= LAST and predicate(chr(code))
        if inside and start is None:
            start = code
        elif not inside and start is not None:
            rows.append("    {0x%X, 0x%X}," % (start, code - 1))
            start = None
    return ["static const CodeRange %s[] = {" % name, *rows, "};"]


lines = [
    "// Generated by generate_unicode_tables.py from Python %s; do not edit." % sys.version.split()[0],
    "// clang-format off",
    *mapping("caseFoldEntries", "casefold"),
    *mapping("lowerEntries", "lower"),
    *ranges("spaceRanges", str.isspace),
    *ranges("printableRanges", str.isprintable),
    "// clang-format on",
]
Path(__file__).with_name("unicode_table.inc").write_text("\n".join(lines) + "\n", encoding="utf-8")
