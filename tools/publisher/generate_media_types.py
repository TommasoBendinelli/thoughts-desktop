"""Writes mediatypes_table.inc: the media types the Python source publisher
assigns, frozen so every platform answers alike.

The table is Python's built-in strict types overridden by the Apache
mime.types that macOS ships (thoughts-server bundles the same file for
Windows as src/thoughts_server/apache-mime.types). Regenerate with the
Python version the server runs:

  python3 generate_media_types.py <thoughts-server>/src/thoughts_server/apache-mime.types
"""
import mimetypes
import sys
from pathlib import Path

table = mimetypes.MimeTypes(filenames=(sys.argv[1],))
strict = table.types_map[True]
lines = [
    "// Generated by generate_media_types.py from Python %s; do not edit." % sys.version.split()[0],
    "// clang-format off",
]
lines.append("static const MediaTypeEntry mediaTypeEntries[] = {")
for extension in sorted(strict):
    lines.append('    {u"%s", u"%s"},' % (extension.replace('\\', '\\\\').replace('"', '\\"'), strict[extension]))
lines.append("};")
lines.append("static const MediaTypeEntry suffixMapEntries[] = {")
for extension in sorted(table.suffix_map):
    lines.append('    {u"%s", u"%s"},' % (extension, table.suffix_map[extension]))
lines.append("};")
lines.append("static const MediaTypeEntry encodingEntries[] = {")
for extension in sorted(table.encodings_map):
    lines.append('    {u"%s", u"%s"},' % (extension, table.encodings_map[extension]))
lines.append("};")
lines.append("// clang-format on")
Path(__file__).with_name("mediatypes_table.inc").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"{len(strict)} types")
