def cli_path() -> str:
    configured = os.environ.get("THOUGHTSCTL")
    if configured:
        return configured
    if sys.platform == "win32":
        # The release installer sets THOUGHTSCTL; tools/windows/build.ps1 installs into the Craft root.
        installed = os.path.join(os.environ.get("LOCALAPPDATA", ""), "Programs", "Thoughts", "bin", "thoughtsctl.exe")
        if os.path.exists(installed):
            return installed
        return shutil.which("thoughtsctl") or r"C:\CraftRoot\bin\thoughtsctl.exe"
    return "/Applications/Thoughts.app/Contents/MacOS/thoughtsctl"


