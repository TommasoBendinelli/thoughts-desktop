@mcp.tool(annotations=ToolAnnotations(title="Send a note to the phone", readOnlyHint=False, destructiveHint=False, idempotentHint=True, openWorldHint=True))
async def send_note(
    title: Annotated[str, Field(min_length=1, max_length=200, description="Short title, shown on the phone and in its notification.")],
    image_path: Annotated[str | None, Field(max_length=4096, description="Absolute path of a PNG or JPEG to send as is (at most 8192 px per side, 40 megapixels, 20 MiB).")] = None,
    html: Annotated[str | None, Field(max_length=2000000, description="A complete HTML page to render (480 CSS px wide, 2.5x). Self-contained: inline styles, inline <svg>, pictures as data: URIs. Scripts do not run and nothing is loaded from the network or from files; use markdown for math.")] = None,
    html_path: Annotated[str | None, Field(max_length=4096, description="Absolute path of an HTML file to render like html; pictures and style sheets it names inside its own folder are put into the page.")] = None,
    markdown: Annotated[str | None, Field(max_length=1000000, description="Markdown to render; math in $...$, $$...$$, \\(...\\) or \\[...\\] is typeset with KaTeX.")] = None,
    message: Annotated[str | None, Field(max_length=4000, description="Optional text shown above the image on the phone.")] = None,
    review_card_id: CardId = None,
    document_id: DocumentId = None,
    document_filename: Annotated[str | None, Field(max_length=512, description="Library PDF filename, informational.")] = None,
    conversation_id: Annotated[str | None, Field(max_length=128, description="Current agent conversation ID, recorded as the note's origin.")] = None,
    note_id: Annotated[str | None, Field(pattern=UUID_PATTERN, description="UUID for this note; omit to generate one. Retrying with the same note_id and content does not send twice.")] = None,
) -> CallToolResult:
    """Send a picture to the user's phone in Thoughts, where they can draw on it (pen, highlighter, colours) and send it back.

    Give exactly one of image_path, html, html_path or markdown. HTML and Markdown are rendered
    on this Mac with headless Google Chrome as a phone-width page (480 CSS px at 2.5x, i.e.
    1200 px wide), as tall as the content up to 8192 px (taller pages are clipped; see warnings).
    The page is rendered in isolation: its scripts do not run, and it can load nothing from the
    network or from files, only inline styles and data: pictures (warnings name what was left
    out). Typeset math with markdown, where $...$ goes through KaTeX. image_path and html_path
    must not lead into hidden folders of the home directory, ~/Library or system folders.
    How to write a note:
    - Diagram first. When answering a photo of the user's page, redraw their diagram in their
      layout (same grid, labels, boxes and arrows), with their marks in black. Draw corrections
      on top of it: strike through or circle what is wrong, and write the fix next to it. Don't
      replace their figure with a generic table or with prose.
    - Explain a mechanism as a small schematic (boxes and arrows in inline <svg>) rather than a
      paragraph.
    - Text: at most 3 short lines under the picture, one idea per line. Over ~40 words means it
      is too long; split it into two notes.
    - Colour like a teacher's pen: text is black; red (#c62828) only on what is wrong, green
      (#2e7d32) only on what is right, grey for neutral background (e.g. masked cells). Never
      colour whole sentences.
    - One topic per note, with a title that says what it covers.
    - Inside <svg>, use <tspan font-weight="700"> for bold; HTML tags like <b> don't render there.
    - Sources: wrap a reference in a link and the user can tap it on the phone. A page of a Library
      PDF: <a href="<Library filename>.pdf#page=53">p. 53</a> (the page as printed, 1-based; #page=N
      alone means document_filename's PDF); a paper or web page: <a href="https://arxiv.org/abs/…">.
      Links inside <svg> work too. Other links are dropped with a warning.
    When the note answers a reply or a page, follow the user's answering rules (get_note_reply and
    get_note hand them over with the reply or page; note_rules shows them).
    Attach the note to a review card
    (review_card_id; the server then fills document_id and the card's question) or a document,
    so the user finds it again from that card or document. The note records this conversation
    (its link opens from the phone's Agent notes); it does not list the conversation under the
    card's or document's Project.
    Returns note_id, delivery.live (a phone is listening right now), listeners, deliveries (the
    phones that already stored this note; empty for a new note), reply_listening.state
    ("listening" when this conversation runs thoughts-watch-replies or waits in get_note_reply;
    otherwise the phone shows the user that no agent is listening for their reply), the local folder
    and image path (~/Thoughts/agent-notes/<time>-<title>-<id8>/note.png), the image size, links
    (each tappable link's target and text), warnings and next_step: what to do or tell the user now. Errors: renderer_unavailable or
    render_failed (send a PNG via image_path instead), path_refused (the file is in a private
    location), unsupported_image, agent_note_too_large, no_credentials, server_unreachable.
    """
    absolute_path(image_path, "image_path")
    absolute_path(html_path, "html_path")
    # The note carries its conversation (opened from the phone's Agent notes); a study conversation
    # is not listed under the Projects or review cards its notes are about.
    valid_id = conversation_id if conversation_id and UUID.fullmatch(conversation_id) else None
    try:
        conversation = await asyncio.to_thread(current_conversation, valid_id)
    except Exception as error:  # the link is optional: never fail the note over it
        print(f"thoughts MCP: note sent without its conversation: {error}", file=sys.stderr)
        conversation = None
    return tool_result(await agent_note_call(
        agent_notes.send_note, title, image_path=image_path, html=html, html_path=html_path, markdown=markdown, message=message,
        review_card_id=review_card_id, document_id=document_id, document_filename=document_filename,
        conversation_id=conversation_id, note_id=note_id, conversation=conversation))


