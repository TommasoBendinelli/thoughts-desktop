async def command(*args: str, payload: dict | None = None, timeout: float = 25) -> dict:
    try:
        process = await asyncio.create_subprocess_exec(
            cli_path(), "--json", *args, stdin=asyncio.subprocess.PIPE if payload is not None else asyncio.subprocess.DEVNULL,
            stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE,
            # Marks a withdrawal as the agent's own decision (protocol/agent-proposals.md section 10).
            env={**os.environ, "THOUGHTS_REQUEST_ORIGIN": "mcp"}, **SUBPROCESS_OPTIONS
        )
    except OSError as error:
        raise RuntimeError(f"Cannot launch thoughtsctl: {error}") from error
    try:
        data = json.dumps(payload, ensure_ascii=False).encode("utf-8") if payload is not None else None
        stdout, stderr = await asyncio.wait_for(process.communicate(data), timeout=timeout)
    except asyncio.TimeoutError as error:
        process.kill()
        await process.communicate()
        raise RuntimeError("Thoughts did not respond in time; the action may already have started. Do not automatically retry Sync. Retry proposal or card creation calls only with identical arguments and the same request_id.") from error
    try:
        result = json.loads(stdout)
        if not isinstance(result, dict) or result.get("schema_version") != 1:
            raise ValueError("Unexpected command response")
    except (ValueError, UnicodeDecodeError) as error:
        detail = stderr.decode(errors="replace").strip()[:1000]
        raise RuntimeError(f"Thoughts command failed: {detail or 'invalid response'}") from error
    if process.returncode and not result.get("error_code"):
        result["error_code"] = "command_failed"
    return result


def tool_result(result: dict, is_error: bool | None = None, extra: list | None = None) -> CallToolResult:
    return CallToolResult(
        content=[TextContent(type="text", text=json.dumps(result, ensure_ascii=False)), *(extra or [])],
        structuredContent=result,
        isError=(bool(result.get("error_code")) or result.get("accepted") is False) if is_error is None else is_error,
    )


@mcp.tool(annotations=ToolAnnotations(title="Open document in Thoughts", readOnlyHint=False, destructiveHint=False, idempotentHint=True, openWorldHint=False))
async def open_document(
    document: Annotated[str, Field(min_length=1, description="Absolute local PDF path, or exact filename in the Thoughts Library, including .pdf.")],
    page: Annotated[int, Field(strict=True, ge=1, le=2147483647, description="One-based PDF page number, not a printed page label.")] = 1,
) -> CallToolResult:
    """Open a PDF at a specific page in the native Thoughts window, reusing an existing tab when possible.

    Returns the document path, actual page and page count after navigation.
    """
    if "\x00" in document or not document.lower().endswith(".pdf"):
        raise ValueError("Provide a PDF path or Library filename.")
    if not Path(document).is_absolute() and ("/" in document or "\\" in document or document.startswith("-")):
        raise ValueError("Use an absolute PDF path or a plain Library filename.")
    return linked(tool_result(await command("open", "--page", str(page), "--", document)), "open_document", {"document": document})


