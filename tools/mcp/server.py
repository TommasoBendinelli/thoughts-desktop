# Protocol: thoughts-server protocol/agent-notes.md. The adapter talks to the Thoughts server
# directly with this Mac's device token; the app does not need to run.

async def run_blocking(function, *args, **kwargs):
    """Run blocking HTTP/Chrome work in a daemon thread (a long-poll must not delay shutdown)."""
    loop = asyncio.get_running_loop()
    future = loop.create_future()

    def settle(result, error):
        if not future.done():
            future.set_exception(error) if error is not None else future.set_result(result)

    def target():
        try:
            result, error = function(*args, **kwargs), None
        except BaseException as caught:  # delivered to the awaiting tool call
            result, error = None, caught
        with contextlib.suppress(RuntimeError):  # loop already closed
            loop.call_soon_threadsafe(settle, result, error)

    threading.Thread(target=target, daemon=True, name="agent-notes-call").start()
    return await future


async def agent_note_call(function, *args, **kwargs) -> dict:
    try:
        return await run_blocking(function, *args, **kwargs)
    except agent_notes.AgentNoteError as error:
        return error.as_dict()
    finally:
        with contextlib.suppress(Exception):
            ensure_reply_watcher()


