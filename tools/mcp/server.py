IMPORT_DOWNLOAD_LIMIT = 200 * 1024 * 1024


def public_addresses(host: str, port: int, resolve=None) -> list:
    """The addresses @p host resolves to, if every one of them is a public Internet address.

    An agent chooses the URL, and what the download returns ends up in the Library: a URL that
    names this computer, the local network or a cloud metadata service (directly, or through a
    name that resolves there) is refused, so import_pdf cannot be used to read services that
    only this computer can reach.
    """
    try:
        found = sorted({info[4][0] for info in (resolve or socket.getaddrinfo)(host, port, type=socket.SOCK_STREAM)})
    except (OSError, UnicodeError) as error:
        raise ValueError(f"The host of the URL could not be resolved: {error}") from None
    for text in found:
        address = ipaddress.ip_address(text.split("%", 1)[0])
        address = getattr(address, "ipv4_mapped", None) or address
        if not address.is_global or address.is_multicast:
            raise ValueError("url must name a public Internet host, not this computer or a private network.")
    if not found:
        raise ValueError("The host of the URL has no address.")
    return found


class PublicHTTPSConnection(http.client.HTTPSConnection):
    """Connects only to an address public_addresses() accepted, so the check and the connection agree."""

    def connect(self):
        last_error = None
        for address in public_addresses(self.host, self.port):
            try:
                self.sock = socket.create_connection((address, self.port), self.timeout)
                break
            except OSError as error:
                last_error = error
        else:
            raise last_error or OSError("no address")
        self.sock = self._context.wrap_socket(self.sock, server_hostname=self.host)


class PublicHTTPSHandler(urllib.request.HTTPSHandler):
    def https_open(self, request):
        return self.do_open(PublicHTTPSConnection, request, context=self._context)


class NoPlainHTTP(urllib.request.HTTPHandler):
    def http_open(self, request):
        raise urllib.error.URLError("the download was redirected to an address that is not https")


def checked_download_url(url: str) -> str:
    parts = urllib.parse.urlsplit(url)
    if parts.scheme != "https" or not parts.hostname or parts.username or parts.password:
        raise ValueError("url must be an https URL without a user name.")
    return url


def download_pdf(url: str, directory: str) -> str:
    """Download @p url into @p directory and return the PDF's path.

    Only https, only from public hosts (every redirect is checked the same way), without proxies.
    """
    checked_download_url(url)
    opener = urllib.request.build_opener(urllib.request.ProxyHandler({}), NoPlainHTTP(),
                                         PublicHTTPSHandler(context=agent_notes.ssl_context()))
    request = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 (Thoughts import_pdf)"})
    try:
        with opener.open(request, timeout=120) as response:
            data = response.read(IMPORT_DOWNLOAD_LIMIT + 1)
    except urllib.error.URLError as error:
        raise ValueError(f"The PDF could not be downloaded: {getattr(error, 'reason', error)}") from None
    if len(data) > IMPORT_DOWNLOAD_LIMIT:
        raise ValueError("The PDF is larger than 200 MiB.")
    if not data.startswith(b"%PDF-"):
        raise ValueError("The URL did not return a PDF (for arXiv use the /pdf/ link).")
    path = os.path.join(directory, "download.pdf")
    Path(path).write_bytes(data)
    return path


@mcp.tool(annotations=ToolAnnotations(title="Import PDF into a Thoughts project", readOnlyHint=False, destructiveHint=False, idempotentHint=True, openWorldHint=True))
async def import_pdf(
    project: Annotated[str, Field(min_length=1, max_length=2000, description="Project name (case-insensitive) or id, e.g. from create_project.")],
    name: Annotated[str, Field(min_length=1, max_length=150, description="Document name shown in the Library, e.g. the paper title.")],
    path: Annotated[str | None, Field(max_length=4096, description="Absolute path of a local PDF file.")] = None,
    url: Annotated[str | None, Field(max_length=4096, description="Or an https URL of a public web site that returns the PDF; it is downloaded and kept as the document's source link.")] = None,
) -> CallToolResult:
    """Import a PDF into a Library project, exactly as Import document in the Library does.

    Give exactly one of path or url. Thoughts copies the PDF into the project and queues its import, so the
    next Sync (start_sync) uploads it to the server. Importing a PDF the project already has changes nothing and
    reports replayed: true. The result names the document (document_id, filename) for links and review cards.
    """
    if (path is None) == (url is None):
        raise ValueError("Give exactly one of path or url.")
    payload = dict(project=project, name=name)
    with contextlib.ExitStack() as stack:
        if url is not None:
            checked_download_url(url)
            import tempfile
            directory = stack.enter_context(tempfile.TemporaryDirectory(prefix="thoughts-import-"))
            payload.update(path=await asyncio.to_thread(download_pdf, url, directory), link=url)
        else:
            # The imported PDF is uploaded with the next Sync: private locations are refused.
            try:
                payload.update(path=str(agent_notes.readable_path(os.path.abspath(os.path.expanduser(path)), "path")))
            except agent_notes.AgentNoteError as error:
                raise ValueError(error.detail) from None
        result = tool_result(await command("import-document", payload=payload))
    return linked(result, "import_pdf", {"project": (result.structuredContent or {}).get("project_id")})


