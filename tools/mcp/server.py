@mcp.tool(annotations=ToolAnnotations(title="Start Thoughts Sync", readOnlyHint=False, destructiveHint=False, idempotentHint=False, openWorldHint=True))
async def start_sync(
    target: Annotated[str | None, Field(description="Optional exact Library PDF filename; omit to Sync all documents.")] = None,
) -> CallToolResult:
    """Start the normal Thoughts Sync workflow, including configured source publication and synchronization.

    Returns immediately with an operation ID; accepted/queued/running does not mean completed.
    Read the returned status_uri to check completion or failure.
    """
    args = ["sync"]
    if target is not None:
        if not target or not target.lower().endswith(".pdf") or any(c in target for c in ("/", "\\", "\x00")) or target.startswith("-"):
            raise ValueError("target must be an exact Library PDF filename.")
        args += ["--target", target]
    result = await command(*args)
    if result.get("operation_id"):
        result["status_uri"] = f"thoughts://sync/{result['operation_id']}"
    return tool_result(result)


@mcp.resource("thoughts://sync/{operation_id}", mime_type="application/json")
async def sync_status(operation_id: str) -> str:
    """Read durable progress and completion of a previously started Thoughts Sync operation."""
    if not operation_id or len(operation_id) > 200 or any(c not in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-_" for c in operation_id):
        raise ValueError("Invalid Sync operation ID.")
    return json.dumps(await command("status", "--", operation_id), ensure_ascii=False)


